export type IconName = keyof typeof registry;

export const iconNames = Object.keys(registry).sort() as IconName[];

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {
  name: IconName;
  /** 像素尺寸；默认跟随字体大小（1em），由容器组件的 CSS 约束。 */
  size?: number;
}

/** 装饰性图标：默认 aria-hidden，需要可读名称时由外层控件提供 aria-label。 */
export function Icon({ name, size, className, strokeWidth = 1.8, ...rest }: IconProps) {
  const Glyph = registry[name];
  return (
    <Glyph
      aria-hidden="true"
      focusable="false"
      width={size}
      height={size}
      strokeWidth={strokeWidth}
      className={cx('ds-icon', className)}
      {...rest}
    />
  );
}
